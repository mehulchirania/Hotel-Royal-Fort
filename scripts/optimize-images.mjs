/**
 * Generates responsive WebP variants for the site.
 *
 * Sources live in assets/images-src/ and are deliberately NOT inside public/,
 * so the 2–2.5 MB originals never ship to the browser — only the generated
 * WebP variants in public/images/ do. Drop a new photo into the source folder
 * and run `npm run optimize:images` to regenerate.
 */
import { mkdir, readdir, stat, writeFile } from 'node:fs/promises';
import { join, parse } from 'node:path';
import sharp from 'sharp';

const SRC = 'assets/images-src';
const OUT = 'public/images';
const WIDTHS = [640, 1024, 1600];
const QUALITY = 76;

/** Single wide image for OpenGraph / schema.org, which want a real bitmap URL. */
const SOCIAL = { from: 'hotel-exterior', file: 'social-card.jpg', width: 1200, height: 630 };

const kb = (n) => `${(n / 1024).toFixed(0)} KB`;

await mkdir(OUT, { recursive: true });

const files = (await readdir(SRC)).filter((f) => /\.(png|jpe?g)$/i.test(f));
if (files.length === 0) {
  console.log('No source images found in', SRC);
  process.exit(0);
}

let before = 0;
let after = 0;
const manifest = {};

for (const file of files) {
  const { name } = parse(file);
  const src = join(SRC, file);
  const original = (await stat(src)).size;
  before += original;

  const meta = await sharp(src).metadata();
  // Never upscale past the source.
  const widths = WIDTHS.filter((w) => w <= meta.width);
  if (widths.length === 0) widths.push(meta.width);

  const variants = [];
  for (const width of widths) {
    const out = join(OUT, `${name}-${width}.webp`);
    const info = await sharp(src).resize({ width }).webp({ quality: QUALITY }).toFile(out);
    after += info.size;
    variants.push({ width, height: info.height, file: `/images/${name}-${width}.webp` });
    console.log(`  ${name}-${width}.webp  ${kb(info.size)}`);
  }

  manifest[name] = {
    aspectRatio: +(meta.width / meta.height).toFixed(4),
    widths: variants.map((v) => v.width),
    src: variants[variants.length - 1].file,
    srcSet: variants.map((v) => `${v.file} ${v.width}w`).join(', '),
  };
  console.log(`${file}: ${kb(original)} -> ${variants.length} webp variants\n`);
}

// Social/schema card — crawlers and chat apps want a plain JPEG at a fixed size.
{
  const socialSrc = files.find((f) => parse(f).name === SOCIAL.from);
  if (socialSrc) {
    const info = await sharp(join(SRC, socialSrc))
      .resize({ width: SOCIAL.width, height: SOCIAL.height, fit: 'cover' })
      .jpeg({ quality: 82, mozjpeg: true })
      .toFile(join(OUT, SOCIAL.file));
    after += info.size;
    console.log(`${SOCIAL.file}  ${kb(info.size)} (${SOCIAL.width}x${SOCIAL.height})\n`);
  }
}

await writeFile(
  'src/data/images.generated.ts',
  `// AUTO-GENERATED by scripts/optimize-images.mjs — do not edit by hand.\n` +
    `// Run \`npm run optimize:images\` to regenerate.\n\n` +
    `export interface ImageAsset {\n  aspectRatio: number;\n  widths: number[];\n  src: string;\n  srcSet: string;\n}\n\n` +
    `export const images = ${JSON.stringify(manifest, null, 2)} as const satisfies Record<string, ImageAsset>;\n\n` +
    `export type ImageName = keyof typeof images;\n`
);

console.log(`Total: ${kb(before)} -> ${kb(after)} (${(100 - (after / before) * 100).toFixed(0)}% smaller)`);
